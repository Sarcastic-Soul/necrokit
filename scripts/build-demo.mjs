// Regenerates site/demo-data.js from the real core rules and fixtures.
// Run from repo root: node --import ./apps/repo-reaper/src/register.mjs scripts/build-demo.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const generatedAt = "2026-10-31T00:00:00.000Z";

const pkgMod = await import(resolve(root, "apps/package-graveyard/src/run.ts"));
const repoMod = await import(resolve(root, "apps/repo-reaper/src/run.ts"));

const pkgFixture = JSON.parse(readFileSync(resolve(root, "apps/package-graveyard/src/fixtures/abandoned.json"), "utf8"));
const repoFixture = JSON.parse(readFileSync(resolve(root, "apps/repo-reaper/src/fixtures/neglected.json"), "utf8"));

const summarize = (report, note) => ({
  subject: report.subject,
  kind: report.kind,
  note,
  score: report.score,
  findings: report.findings.map((f) => ({ severity: f.severity, title: f.title, explanation: f.explanation })),
  plan: report.plan.steps.map((s) => s.action),
});

const data = {
  pkg: summarize(pkgMod.scanPackage(pkgFixture, generatedAt), "Synthetic abandoned-package fixture."),
  repo: summarize(repoMod.scanRepository(repoFixture, generatedAt), "Synthetic neglected-repository fixture."),
};

writeFileSync(
  resolve(root, "site/demo-data.js"),
  `// Generated by scripts/build-demo.mjs. Do not edit by hand.\nexport const DEMO = ${JSON.stringify(data, null, 2)};\n`,
);
console.log("wrote site/demo-data.js");
